export function Sidebar() {
  const pathname = usePathname();
  const { sidebarOpen, toggleSidebar } = useUIStore();

  return (
    <aside
      className={clsx(
        "fixed left-0 top-0 z-40 flex h-screen flex-col border-r border-neutral-800 bg-neutral-900 transition-all duration-300",
        sidebarOpen ? "w-64" : "w-16",
      )}
    >
      <div className="flex h-16 items-center justify-between border-b border-neutral-800 px-4">
        {sidebarOpen && (
          <Link href="/dashboard" className="text-xl font-bold">
            Chess<span className="text-green-500">toire</span>
          </Link>
        )}
        <button
          type="button"
          onClick={toggleSidebar}
          className="rounded-lg p-2 text-neutral-400 hover:bg-neutral-800 hover:text-white"
          aria-label={sidebarOpen ? "Collapse sidebar" : "Expand sidebar"}
        >
          <MenuIcon />
        </button>
      </div>

      <nav className="flex-1 space-y-1 p-2">
        {navItems.map((item) => {
          const isActive = pathname === item.href || pathname.startsWith(`${item.href}/`);
          return (
            <Link
              key={item.href}
              href={item.href}
              className={clsx(
                "flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium transition-colors",
                isActive
                  ? "bg-green-600/20 text-green-500"
                  : "text-neutral-400 hover:bg-neutral-800 hover:text-white",
              )}
            >
              <item.icon className="h-5 w-5 flex-shrink-0" />
              {sidebarOpen && <span>{item.label}</span>}
            </Link>
          );
        })}
      </nav>

      <div className="border-t border-neutral-800 p-4">
        {sidebarOpen && (
          <div className="text-xs text-neutral-500">
            <p>Chesstoire v0.1.0</p>
          </div>
        )}
      </div>
    </aside>
  );
}

